def page_responses() -> str:
    env = "\n".join(f"| `{k}` | {t} | {d} |" for k, (t, d) in ENVELOPE_DOCS.items())
    per = []
    for ep, rows in ENDPOINT_EXTRA.items():
        per.append(f"### `{ep}`\n\n| Key | Type | Meaning |\n|---|---|---|\n"
                   + "\n".join(f"| `{k}` | {t} | {d} |" for k, t, d in rows))
    dep = "\n".join(f"| `deprecation.{k}` | {t} | {d} |" for k, t, d in DEPRECATION_DOCS)
    return GENERATED + f"""# Responses

Every response is a JSON object that starts with the same envelope:

| Key | Type | Meaning |
|---|---|---|
{env}

`schools.json` and `index.json` cover all schools, so they have no `school` key.

On a **deprecated** version, every response also has:

| Key | Type | Meaning |
|---|---|---|
{dep}

See [versions.md](versions.md).

## Keys after the envelope, by endpoint

{chr(10).join(chr(10) + p for p in per)}

An "activity" is the object described in [fields.md](fields.md).
"""


def page_fields() -> str:
    rows = field_rows()
    faculties = sorted({f for m in SCHOOLS.values() for f in m.SCHOOL_INFO["faculties"]})
    for r in rows:
        if r["path"] == "faculty":
            r["values"] = faculties
        if r["path"] == "subfaculty":
            r["description"] += " Valid values per faculty are listed in filters.md."
    i = next(n for n, r in enumerate(rows) if r["path"] == "provenance") + 1
    rows[i:i] = [
        {"path": "provenance.<field>.method", "type": "string", "values": list(METHOD_DOCS),
         "description": "How that field's value was decided (see the table below)."},
        {"path": "provenance.<field>.evidence", "type": "string or null", "values": [],
         "description": "Why: the matched listing text, the recruitment posting, or the maintainer's note."},
    ]
    lines = []
    for r in rows:
        vals = ", ".join(f"`{v}`" for v in r["values"])
        lines.append(f"| `{r['path']}` | {r['type']} | {vals} | {_md_escape(r['description'])} |")
    methods = "\n".join(f"| `{k}` | {v} |" for k, v in METHOD_DOCS.items())
    kw = ", ".join(f"`{t}`" for t in sorted(infer.TAG_RULES))
    return GENERATED + f"""# Fields of an activity

Every activity, wherever it appears (`all`, `item`, `filter`, `tag`), has exactly these fields.
Paths use dots for nested objects and `[]` for items inside a list.

| Field | Type | Allowed values | Meaning |
|---|---|---|---|
{chr(10).join(lines)}

## `null` means unknown

Most directories don't list hours, meeting times or application windows, so many of those
fields are `null`. A value is never guessed to fill a gap.

## `provenance.<field>.method`

| Method | Meaning |
|---|---|
{methods}

Fields with no `provenance` entry were copied straight from the listing.

## Tags

`tags` combines:

- the directory's own categories, lowercased and hyphenated (e.g. AMS "Science & Engineering" becomes `science-engineering`);
- the activity's `type` and `subfaculty`;
- keyword tags matched from the name and description: {kw}.

The full live list with counts is at `{V}/{{school}}/tags.json`.

## Machine-readable

The same fields, with exact JSON types, are recorded in
[`contracts/{V}.json`](../contracts/{V}.json). Within {V}, fields are only ever added, never removed or
changed in type (see [versions.md](versions.md)).
"""


def page_versions() -> str:
    reg = versions.load_registry()
    rows = []
    for v, e in sorted(reg.items(), key=lambda kv: int(kv[0][1:])):
        rows.append(f"| `{v}` | {e['status']} | {e.get('released') or 'not yet published'} | "
                    f"{e.get('deprecated_since') or ''} | {e.get('successor') or ''} | {e.get('sunset') or ''} | "
                    f"{e.get('data_frozen_at') or ''} |")
    dep = "\n".join(f"| `{k}` | {t} | {d} |" for k, t, d in DEPRECATION_DOCS)
    return GENERATED + f"""# Versions

Every path starts with an API version (`{V}/…`). The current version is **{V}**.

| Version | Status | Released | Deprecated since | Successor | Sunset | Data frozen at |
|---|---|---|---|---|---|---|
{chr(10).join(rows)}

The live version of this table is `versions.json` at the site root.

## The promise

Within a version, URLs, filter values and fields are only ever **added**. Nothing is removed or
renamed, and no field changes type. Anything that would break existing code ships as a new
version. The repository enforces this automatically: a change that breaks the current version's
contract ([`contracts/{V}.json`](../contracts/{V}.json)) can't be deployed.

## When a new version comes out

The old version **keeps working**, but:

- its data is **frozen** at the moment it was replaced and no longer updates;
- every response in it has `"deprecated": true` and a `deprecation` object:

| Key | Type | Meaning |
|---|---|---|
{dep}

Responses from the current version always have `"deprecated": false`, so one check works everywhere:

```js
const data = await (await fetch(url)).json();
if (data.deprecated) console.warn(data.deprecation.message);
```

A deprecated version may be removed after its `sunset` date. If no sunset date is set, it stays.
"""


def page_school(sid: str, mod) -> str:
    info = mod.SCHOOL_INFO
    by_id = {s.SOURCE_ID: s for s in mod.SOURCES}
    fac = []
    for f, finfo in info["faculties"].items():
        srcs = ", ".join(f"`{s}`" for s in finfo.get("sources", [])) or "none yet"
        fac.append(f"### `fac-{f}`: {finfo['name']}\n\n{finfo['description']}.\n\n"
                   f"- Sources: {srcs}\n"
                   f"- All of it: `{V}/{sid}/filter/fac-{f}/sub-any/type-any/app-any/first-any.json`\n")
        subs = finfo.get("subfaculties", {})
        if subs:
            fac[-1] += "\n| Subfaculty | What it is | URL |\n|---|---|---|\n" + "\n".join(
                f"| `sub-{s}` | {name} | `{V}/{sid}/filter/fac-{f}/sub-{s}/type-any/app-any/first-any.json` |"
                for s, name in subs.items())
            fac[-1] += "\n"
    src_rows = "\n".join(
        f"| `{s.SOURCE_ID}` | {s.SOURCE_NAME} | {_src_url(s)} | {(s.__doc__ or '').strip().splitlines()[0]} |"
        for s in mod.SOURCES)
    floors = getattr(mod, "MIN_ITEMS_PER_SOURCE", {})
    return GENERATED + f"""# {info['name']} (`{sid}`)

{info.get('location', '')}

- Everything: `{V}/{sid}/all.json`
- Live counts, freshness and filter values: `{V}/{sid}/info.json`

## Faculties

Every faculty below has working filter URLs, even when it has no source yet (those return an
empty list until one is added).

{chr(10).join(fac)}
## Sources

| Source id | Directory | URL | What it provides |
|---|---|---|---|
{src_rows}

Each activity says which source it came from in `source.id`, and any other directory that
lists it in `also_listed_in`. If a source's website is down, the most recent Internet Archive
copy is used, and `info.json → sources[].via` says `wayback`.

Expected minimum activities per source (a build with fewer is treated as a broken scraper and
not published): {", ".join(f"`{k}` ≥ {v}" for k, v in floors.items()) or "none"}.

## Item ids

Ids are prefixed by their directory: `ams-`, `engsoc-`, `compsa-`, `hss-`, `comsoc-`, `rec-`.
They stay the same across updates as long as the activity keeps its name.

## Freshness

We attempt to collect every source once a week. A collection can fail (a site is down, or its
page changes), and then the last good copy is kept, so some data may be older than a week.
Check `data_as_of` in any response, and `info.json → sources[].fetched_at` for each source.
"""


def render() -> dict[str, str]:
    pages = {
        "README.md": page_index(),
        "endpoints.md": page_endpoints(),
        "filters.md": page_filters(),
        "responses.md": page_responses(),
        "fields.md": page_fields(),
        "versions.md": page_versions(),
    }
    for sid, mod in SCHOOLS.items():
        pages[f"schools/{sid}.md"] = page_school(sid, mod)
    return pages


def write(docs: Path = DOCS) -> list[Path]:
    out = []
    for rel, text in render().items():
        p = docs / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        out.append(p)
    return out


def check(docs: Path = DOCS) -> list[str]:
    """Pages that are missing or differ from what the code would generate."""
    stale = []
    for rel, text in render().items():
        p = docs / rel
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            stale.append(rel)
    return stale


