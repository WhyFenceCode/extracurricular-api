def _md_escape(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def _type_label(types: set[str]) -> str:
    nullable = "null" in types
    rest = sorted(t for t in types if t != "null")
    names = {"string": "string", "number": "number", "integer": "integer", "boolean": "boolean",
             "object": "object", "array<string>": "array of strings", "array<integer>": "array of integers",
             "array<object>": "array of objects"}
    label = " or ".join(names.get(t, t) for t in rest) or "any"
    return f"{label} or null" if nullable else label


def _resolve(node: dict, defs: dict) -> dict:
    while "$ref" in node:
        node = defs[node["$ref"].split("/")[-1]]
    return node


def _fields(node: dict, defs: dict, prefix: str, rows: list[dict]) -> None:
    desc = node.get("description")
    node_r = _resolve(node, defs)
    desc = desc or node_r.get("description")
    variants = node_r.get("anyOf") or [node_r]
    types, enums, child = set(), [], None
    for v in variants:
        v = _resolve(v, defs)
        if "enum" in v:
            types.add("string"); enums += v["enum"]
        elif "const" in v:
            types.add("string"); enums.append(v["const"])
        elif v.get("type") == "array":
            it = _resolve(v.get("items", {}), defs)
            types.add("array<object>" if "properties" in it else f"array<{it.get('type', 'any')}>")
            if "properties" in it:
                child = it
        elif v.get("type") == "object" and "properties" in v:
            types.add("object"); child = v
        elif v.get("type") == "object" and "additionalProperties" in v:
            types.add("object")
        else:
            types.add(v.get("type", "any"))
    if prefix:
        rows.append({"path": prefix, "type": _type_label(types), "values": enums, "description": desc or ""})
    if child is not None:
        sub_prefix = f"{prefix}[]" if any(t.startswith("array") for t in types) else prefix
        for name, sub in child["properties"].items():
            _fields(sub, defs, f"{sub_prefix}.{name}" if sub_prefix else name, rows)


def field_rows() -> list[dict]:
    schema = Item.model_json_schema()
    rows: list[dict] = []
    _fields(schema, schema.get("$defs", {}), "", rows)
    return rows


def _src_url(mod) -> str:
    for attr in ("DIRECTORY_URL", "LISTING", "URL", "PORTAL", "BASE"):
        if hasattr(mod, attr):
            return getattr(mod, attr)
    return ""


